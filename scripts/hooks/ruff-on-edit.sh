#!/bin/bash
# PostToolUse: линтуем ТОЛЬКО что изменённый Python-файл.
#
# Почему набор урезан до F, а не весь из pyproject. Замер 2026-07-26: полный
# набор (E,F,W,I,B,UP) даёт на существующем коде 160 замечаний, из них 30
# «несортированные импорты» и 29 «старый Optional». Хук, который на каждую
# правку вываливает чужой стилевой долг, выключат в тот же день. F (настоящие
# ошибки: неиспользуемое, неопределённое) — это единицы, и каждое по делу.
#
# ⚠️ Именно F, а не F,B: `--select` в командной строке ПЕРЕБИВАЕТ `ignore` из
# pyproject, поэтому с `B` сюда вернулся бы B008 — идиома `Depends()` в
# аргументах FastAPI, которой в этом коде 98 штук и которая не баг.
#
# Правим по ходу дела, файл за файлом, а не большим разовым прогоном: среди
# «неиспользуемых импортов» есть ре-экспорт фикстур в `backend/tests/conftest.py`,
# и `ruff --fix` по всему репозиторию сломал бы тесты.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RUFF="$REPO/.venv/bin/ruff"

input=$(cat)
file=$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty')

[[ -n "$file" && "$file" == *.py && -f "$file" ]] || exit 0
[[ -x "$RUFF" ]] || exit 0

# --quiet убирает итоговую строку. Без неё «All checks passed!» попадает в
# $out, вывод считается непустым, и хук блокирует КАЖДУЮ правку.
out=$("$RUFF" check --select F --output-format concise --quiet "$file" 2>/dev/null | grep -v '^warning:' || true)

if [[ -n "$out" ]]; then
  {
    echo "ruff (F) в файле, который ты только что изменил:"
    echo "$out"
    echo
    echo "Почини это перед тем, как двигаться дальше. Если срабатывание ложное"
    echo "(например ре-экспорт фикстуры) — добавь точечный # noqa с причиной."
  } >&2
  exit 2
fi
exit 0
