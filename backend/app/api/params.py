"""Типы параметров пути.

`essay_id: int` нигде не был ограничен сверху, и это не косметика. Schemathesis
нашёл 2026-07-26: `9223372036854775808` в пути роняет драйвер БД — `int too
large to convert` на sqlite, `NumericValueOutOfRange` на Postgres, — то есть
**500 вместо 404/422**, на КАЖДОЙ ручке с числовым параметром пути (нашлось
сразу на четырёх). Запрос при этом анонимный: до проверки прав дело не доходит,
падение случается на входе в БД.

Первичные ключи в `models.py` объявлены как `Mapped[int]` без уточнения, то
есть Postgres `integer` (int32). Граница ниже повторяет ровно это: значение
больше int32 не может быть существующей строкой ни при каком раскладе, и
честный ответ на такой запрос — 422 от валидации, а не падение драйвера.
"""
from __future__ import annotations

from typing import Annotated

from fastapi import Path

# Верхняя граница Postgres `integer` — типа, в котором лежат все PK проекта.
PG_INT_MAX = 2**31 - 1

DbId = Annotated[int, Path(ge=1, le=PG_INT_MAX)]
